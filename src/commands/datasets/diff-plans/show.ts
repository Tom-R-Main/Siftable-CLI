import {Args} from '@oclif/core';
import {BaseCommand} from '../../../lib/base-command.js';
import {renderDetail, renderTable} from '../../../lib/output.js';

export default class DatasetsDiffPlansShow extends BaseCommand {
  static description = 'Show a persisted dataset diff plan';

  static args = {
    id: Args.string({description: 'Diff plan ID', required: true}),
  };

  static flags = {
    ...BaseCommand.baseFlags,
  };

  async run(): Promise<unknown> {
    const {args, flags} = await this.parse(DatasetsDiffPlansShow);
    const client = await this.client(flags);
    const response = await client.getDatasetDiffPlan(args.id);
    this.handleApiError(response);
    const result = response.data as { ok: true; plan: Record<string, unknown> };
    const plan = result.plan;

    if (!this.jsonEnabled()) {
      renderDetail([
        ['Plan ID', String(plan.id ?? '')],
        ['Dataset ID', String(plan.datasetId ?? '')],
        ['Status', String(plan.status ?? '')],
        ['Generated by', String(plan.generatedBy ?? '')],
        ['Base version', String(plan.baseVersion ?? '')],
      ]);
      const operations = Array.isArray(plan.proposedOperations) ? plan.proposedOperations as Array<Record<string, unknown>> : [];
      if (operations.length > 0) {
        this.log('');
        renderTable(
          operations.slice(0, 25),
          [
            {key: 'op', header: 'Op'},
            {key: 'rowNumber', header: 'Row'},
            {key: 'existingRecordId', header: 'Record'},
            {key: 'upsertValue', header: 'Upsert', get: (operation) => operation.upsertBy ? `${operation.upsertBy}=${String(operation.upsertValue ?? '')}` : ''},
          ],
        );
      }
    }

    return result;
  }
}
